import prettier from 'prettier';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
export async function onboardingOutputs(sourceRoot = root) {
  const source = await readFile(resolve(sourceRoot, 'docs/agent/SKILL.md'), 'utf8');
  const { version } = JSON.parse(await readFile(resolve(sourceRoot, 'package.json'), 'utf8'));
  if (!/^\d+\.\d+\.\d+(?:-[A-Za-z0-9.-]+)?$/.test(version))
    throw new Error('Invalid release version.');
  if (!source.startsWith('---\nname: opengen\ndescription: '))
    throw new Error('Expected installable opengen frontmatter.');
  const template = source.replaceAll('{{VERSION}}', version);
  const start = template.indexOf('## Choose your runtime\n');
  const end = template.indexOf('## Diagnose and discover\n');
  if (start < 0 || end < start) throw new Error('Missing runtime onboarding section.');
  const skill = template.replaceAll('{{ORIGIN}}', 'https://opengen.dev');
  const guide = await readFile(resolve(sourceRoot, 'docs/IMAGE-TO-VIDEO.md'), 'utf8');
  const guideTemplate = guide
    .replaceAll('https://your-opengen.example', '{{ORIGIN}}')
    .replaceAll('https://opengen.dev', '{{ORIGIN}}');
  const module = `// GENERATED by scripts/build-onboarding.mjs from docs/agent/SKILL.md.\n// Edit the source and regenerate; this module is shared by REST and web.\nconst skillTemplate = ${JSON.stringify(template)};\nconst entryTemplate = ${JSON.stringify(template.slice(start, end))};\nconst guideTemplate = ${JSON.stringify(guideTemplate)};\nconst render = (template: string, origin: string) => template.replaceAll('{{ORIGIN}}', origin.replace(/\\/$/, ''));\nexport const agentSkill = (origin: string): string => render(skillTemplate, origin);\nexport const agentEntry = (origin: string): string => render(entryTemplate, origin);\nexport const imageToVideoGuide = (origin: string): string => render(guideTemplate, origin);\n`;
  const plugin = {
    name: 'opengen',
    version,
    description: 'Exact image/video discovery, authorized generation and safe job recovery.',
    license: 'Apache-2.0',
    homepage: 'https://opengen.dev/agents/claude-code',
    mcpServers: { opengen: { type: 'http', url: 'https://opengen.dev/mcp' } },
  };
  return new Map([
    ['skills/opengen/SKILL.md', skill],
    ['plugins/opengen/skills/opengen/SKILL.md', skill],
    ['plugins/opengen/.claude-plugin/plugin.json', JSON.stringify(plugin, null, 2) + '\n'],
    [
      'packages/contracts/src/onboarding.ts',
      await prettier.format(module, {
        parser: 'typescript',
        singleQuote: true,
        printWidth: 100,
        trailingComma: 'all',
        proseWrap: 'preserve',
      }),
    ],
  ]);
}
export async function buildOnboarding({ check = false } = {}) {
  for (const [path, expected] of await onboardingOutputs()) {
    const target = resolve(root, path);
    if (check) {
      let actual;
      try {
        actual = await readFile(target, 'utf8');
      } catch {
        /* stale/missing */
      }
      if (actual !== expected) throw new Error(`Generated onboarding is stale: ${path}`);
    } else {
      await mkdir(dirname(target), { recursive: true });
      await writeFile(target, expected);
    }
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    if (process.argv.slice(2).some((arg) => arg !== '--check'))
      throw new Error('Use node scripts/build-onboarding.mjs [--check].');
    await buildOnboarding({ check: process.argv.includes('--check') });
    console.log(
      process.argv.includes('--check')
        ? 'Generated onboarding is current.'
        : 'Generated skill, plugin and protocol onboarding.',
    );
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
